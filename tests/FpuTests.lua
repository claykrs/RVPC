			if band(m.cpu.flags, 0x045) ~= v[10] then
				bad = string.format("flags got=%03X want=%03X", band(m.cpu.flags, 0x045), v[10])
			end
		elseif BYTE_RESULT[op] then
			local words = { v[10], v[11], v[12] }
			local count = BYTE_RESULT[op]
