				)
			end
		elseif M80_RESULT[op] or op == 18 or op == 19 or op == 20 then
			local gotLo = m.mem:read32(0x6000 + slotR)
			local gotHi = m.mem:read32(0x6000 + slotR + 4)
			local gotSe = m.mem:read16(0x6000 + slotR + 8)
			if gotLo ~= v[12] or gotHi ~= v[11] or gotSe ~= v[10] then
				bad = string.format(
					"m80 got=%04X|%08X|%08X want=%04X|%08X|%08X",
					gotSe,
					gotHi,
					gotLo,
					v[10],
					v[11],
					v[12]
				)
			end
			if not bad and TWO_STORE[op] then
				local bLo = m.mem:read32(0x6000 + slotB)
				local bHi = m.mem:read32(0x6000 + slotB + 4)
				local bSe = m.mem:read16(0x6000 + slotB + 8)
				if bLo ~= v[9] or bHi ~= v[8] or bSe ~= v[7] then
					bad = string.format(
						"slotB got=%04X|%08X|%08X want=%04X|%08X|%08X",
						bSe,
						bHi,
						bLo,
						v[7],
						v[8],
						v[9]
					)
				end
			end
		end
		if not bad and op ~= 24 and not BYTE_RESULT[op] then
			if band(m.mem:read16(0x6000 + slotSW), swMask) ~= v[13] then
				bad = string.format(
					"sw got=%04X want=%04X",
					band(m.mem:read16(0x6000 + slotSW), swMask),
					v[13]
				)
			end
		end
		if bad then
			failed += 1
			if failed <= 12 then
				print(string.format("vector %s op%d: %s", name, op, bad))
			end
		end
	end
	expect(failed == 0, string.format("%d/%d 80-bit vectors failed", failed, #VECTORS))
