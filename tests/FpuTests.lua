	const slotA, slotB, slotR, slotSW, slotCW = 0x400, 0x410, 0x420, 0x430, 0x434
	const swMask = 0x47FF
	local failed = 0
	for _, v in VECTORS do
		const name, op, cw = v[1], v[2], v[3]
		fpu.top = 0
		fpu.status = 0
		fpu.pendingMf = false
		fpu.control = 0x037F
		for i = 0, 7 do
			fpu.tags[i] = 3
			fpu.rSign[i] = 0
			fpu.rExp[i] = 0
			fpu.rHi[i] = 0
			fpu.rLo[i] = 0
		end
		if op == 18 or op == 19 or op == 20 then
			-- raw operand words (low, mid, high) rather than (se, hi, lo)
			putM80(m, slotA, v[6], v[5], v[4])
		else
			putM80(m, slotA, v[4], v[5], v[6])
		end
		putM80(m, slotB, v[7], v[8], v[9])
		putData(m, slotCW, { band(cw, 0xFF), band(rshift(cw, 8), 0xFF) })

		local code = { 0xD9, 0x2E }
		for k = 0, 3 do
			code[#code + 1] = band(rshift(slotCW, k * 8), 0xFF)
		end
		if op ~= 18 and op ~= 19 and op ~= 20 then
			code[#code + 1] = 0xDB
			code[#code + 1] = 0x2E
			for k = 0, 3 do
				code[#code + 1] = band(rshift(slotA, k * 8), 0xFF)
			end
		end
