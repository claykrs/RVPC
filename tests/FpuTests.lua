T("fpu_ts_lazy_switch", function(expect)
	const m, fpu = newMachine()
	putCode(m, {
		0xD9,
		0xE8, -- FLD1 (TS -> #NM)
		0x0F,
		0x06, -- CLTS
		0xD9,
		0xE8, -- FLD1
		0xDB,
		0xE3, -- FNINIT (TS -> #NM)
		0xDB,
		0xE2, -- FNCLEX (TS -> #NM)
		0x0F,
		0x06, -- CLTS
		0xD9,
		0xE8, -- FLD1
	})
	m.mem:write16(0x1C, 0)
	m.mem:write16(0x1E, 0)
