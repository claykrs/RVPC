			or op == 1
			or op == 2
			or op == 3
			or op == 9
			or op == 10
			or op == 11
			or op == 22
			or op == 23
			or op == 24
			or op == 26
			or op == 27
			or op == 32
		if binaryOp then
			code[#code + 1] = 0xDB
			code[#code + 1] = 0x2E
			for k = 0, 3 do
				code[#code + 1] = band(rshift(slotB, k * 8), 0xFF)
			end
		end
		const opBytes = VECTOR_OPS[op]
		if not BYTE_RESULT[op] then
			for _, byte in opBytes do
				code[#code + 1] = byte
			end
		end
		if op == 18 or op == 19 or op == 20 then
			-- the load's own memory operand sits at slotA
			for k = 0, 3 do
				code[#code + 1] = band(rshift(slotA, k * 8), 0xFF)
			end
		end
